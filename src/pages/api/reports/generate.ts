const COLORS = {
  background: '#F7F0E1',
  primary: '#1E1A14',
  accent: '#8A560A',
  secondary: '#4A4133',
  muted: '#6B5F4B',
  border: '#D6C7A8',
  cardBg: '#F2E7CF',
};

/**
 * Helper function to draw a rounded rectangle
 */
function drawRoundedRect(
  doc: PDFKit.PDFDocument,
  x: number,
  y: number,
  width: number,
  height: number,
  radius: number
) {
  doc
    .moveTo(x + radius, y)
    .lineTo(x + width - radius, y)
    .quadraticCurveTo(x + width, y, x + width, y + radius)
    .lineTo(x + width, y + height - radius)
    .quadraticCurveTo(x + width, y + height, x + width - radius, y + height)
    .lineTo(x + radius, y + height)
    .quadraticCurveTo(x, y + height, x, y + height - radius)
    .lineTo(x, y + radius)
    .quadraticCurveTo(x, y, x + radius, y);
}

/**
 * Add header to content pages
 */
function addPageHeader(doc: PDFKit.PDFDocument, title: string, date: string) {
  const headerY = 40;
  
  doc.fontSize(9).fillColor(COLORS.secondary).font('Helvetica');
  doc.text('Executive Report', 50, headerY, { width: 300, ellipsis: true });
  
  const dateText = date;
  const dateWidth = doc.widthOfString(dateText);
  doc.text(dateText, doc.page.width - 50 - dateWidth, headerY);
  
  doc.moveTo(50, headerY + 18)
     .lineTo(doc.page.width - 50, headerY + 18)
     .strokeColor(COLORS.border)
     .lineWidth(1)
     .stroke();
}

/**
 * Add footer to content pages
 */
function addPageFooter(doc: PDFKit.PDFDocument, pageNum: number) {
  const footerY = doc.page.height - 50;
  
  doc.moveTo(50, footerY)
     .lineTo(doc.page.width - 50, footerY)
     .strokeColor(COLORS.border)
     .lineWidth(1)
     .stroke();
  
  doc.fontSize(9).fillColor(COLORS.secondary).font('Helvetica');
  doc.text('Generated by Procurix', 50, footerY + 10);
  
  const pageText = `Page ${pageNum}`;
  const pageWidth = doc.widthOfString(pageText);
  doc.text(pageText, doc.page.width - 50 - pageWidth, footerY + 10);
}

/**
 * Draw gradient-like background
 */
function drawGradientBackground(doc: PDFKit.PDFDocument) {
  doc.rect(0, 0, doc.page.width, doc.page.height).fill(COLORS.background);
}

interface ReportData {
  title: string;
  includeAnalytics: boolean;
  timestamp: string;
  preAnalyzedData?: {
    workCompleted: string[];
    keyDecisions: string[];
    problemsSolved: string[];
    insights: string[];
    actionItems: string[];
    summary?: string;
  };
}

interface ChatMessage {
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
}

// ADD THIS near the bottom of generate.ts, outside the default handler

export async function generateReportFromData(input: {
  title: string;
  includeAnalytics: boolean;
  timestamp: string;
  chatHistory: any[];
  preAnalyzedData?: ReportData['preAnalyzedData'];
}) {
  // Mirror what the handler does:

  triggerBackgroundCleanup();

  const { title, includeAnalytics, preAnalyzedData } = input;

  const chatHistory = input.chatHistory as ChatMessage[];

  const analysis = preAnalyzedData && Object.keys(preAnalyzedData).length > 0
    ? {
        totalMessages: chatHistory.length,
        userMessages: chatHistory.filter(m => m.role === 'user').length,
        assistantMessages: chatHistory.filter(m => m.role === 'assistant').length,
        workCompleted: preAnalyzedData.workCompleted || [],
        keyDecisions: preAnalyzedData.keyDecisions || [],
        problemsSolved: preAnalyzedData.problemsSolved || [],
        insights: preAnalyzedData.insights || [],
        actionItems: preAnalyzedData.actionItems || [],
        topics: [],
        timeRange: {
          start: chatHistory[0]?.timestamp || new Date().toISOString(),
          end: chatHistory[chatHistory.length - 1]?.timestamp || new Date().toISOString(),
        },
      }
    : analyzeChatHistory(chatHistory);

  const pdfBuffer = await generatePDF(title, analysis, includeAnalytics);

  const filename = `executive-report-${format(new Date(), 'yyyy-MM-dd-HHmmss')}-${randomBytes(8).toString('hex')}.pdf`;
  const tmpDir = getReportsDir();
  ensureDir(tmpDir);
  const filePath = path.join(tmpDir, filename);
  fs.writeFileSync(filePath, pdfBuffer);

  // Use relative path for download URL (works better with Vercel)
  const relativePath = `reports/${filename}`;

  // Attempt persistent storage upload (Supabase). This mitigates /tmp ephemeral loss across lambdas.
  let publicDownloadUrl: string | null = null;
  let storageUploaded = false;
  try {
    const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
    if (supabaseUrl && supabaseKey) {
      const bucket = process.env.SUPABASE_REPORTS_BUCKET || 'reports';
      const supabase = createClient(supabaseUrl, supabaseKey);
      const uploadRes = await supabase.storage
        .from(bucket)
        .upload(filename, pdfBuffer, { contentType: 'application/pdf', upsert: true });
      if (uploadRes.error) {
        console.error('[REPORT STORAGE] Upload error:', uploadRes.error.message);
      } else {
        const { data } = supabase.storage.from(bucket).getPublicUrl(filename);
        publicDownloadUrl = data.publicUrl;
        storageUploaded = true;
        console.log('[REPORT STORAGE] Uploaded to Supabase. Public URL:', publicDownloadUrl);
      }
    } else {
      console.log('[REPORT STORAGE] Supabase env vars missing; skipping persistent upload.');
    }
  } catch (storageErr: any) {
    console.error('[REPORT STORAGE] Unexpected storage error:', storageErr.message);
  }

  return {
    success: true,
    filename,
    downloadUrl: publicDownloadUrl || `/api/download-rfp?path=${encodeURIComponent(relativePath)}`,
    filePath,
    publicDownloadUrl,
    storageUploaded,
    pageCount: analysis.workCompleted.length > 0 ? 3 : 2,
    generatedAt: new Date().toISOString(),
    sections: {
      work: analysis.workCompleted.length,
      decisions: analysis.keyDecisions.length,
      problems: analysis.problemsSolved.length,
      insights: analysis.insights.length,
      actions: analysis.actionItems.length,
    },
  };
}

